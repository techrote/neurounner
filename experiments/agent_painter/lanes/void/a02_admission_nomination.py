#!/usr/bin/env python3
"""VOID A02 v5 split-held nomination: exact native evidence, no TRAIN admission.

The output is a review packet, NOT a native-admitted TRAIN row. It cannot
authorize optimization or replace the shared foundation's native admission.
"""
from __future__ import annotations

import argparse
import ast
import json
from pathlib import Path

from adapter import (CyberSandVoidByteTokenizer, FRAMING_ID, MAX_SEQUENCE_TOKENS, encode_row)
from v5_service_slots import (
    CROP_SHA, CORPUS, MODEL, PRODUCER, PROGRAM_SHA, SEEDS,
    native_audit, program_witness,
)

ROOT = Path(__file__).resolve().parent
SYSTEM = (
    "Return only one valid CyberSand painter program JSON object. "
    "Follow the requested structure. Do not set host seeds, material permissions or focus."
)
MODEL_CONTEXT = 2048
EXPECTED_ZIP = "d8f1c1dbce65ef14d392a7bd557bd89e8af21563da14d4a5a61b84386285944b"
EXPECTED_KEYS = {
    "schema", "state", "global_candidate", "family", "model", "program_sha256",
    "original_corpus_source", "original_corpus_manifest_sha256",
    "original_native_source", "original_native_run_id",
    "original_native_artifact_id", "original_native_zip_sha256",
    "original_native_crop_sha256", "native_host_seeds",
    "distinct_compositions", "split", "teacher_origin", "prompt", "semantics",
    "training_admitted", "expanded_shared_train_groups", "final_targets_opened",
    "model_optimizer_steps", "model_generated_paintings", "decision",
}


def require(condition, reason):
    if not condition:
        raise ValueError(reason)


def validate(doc):
    require(type(doc) is dict and set(doc) == EXPECTED_KEYS, "nomination schema/key set differs")
    exact = {
        "schema": "void-a02-v5-admission-nomination/1",
        "state": "REVIEW_ONLY_NOT_ADMITTED",
        "global_candidate": "ARCH-568-R01",
        "family": "architecture",
        "model": MODEL,
        "program_sha256": PROGRAM_SHA,
        "original_corpus_source": "633920373a3d406a2ede61ce4137c324f76be23b",
        "original_corpus_manifest_sha256": CORPUS,
        "original_native_source": PRODUCER,
        "original_native_run_id": 43601866007,
        "original_native_artifact_id": 14116463694,
        "original_native_zip_sha256": EXPECTED_ZIP,
        "original_native_crop_sha256": CROP_SHA,
        "native_host_seeds": list(SEEDS),
        "distinct_compositions": 1,
        "split": "UNADMITTED_TRAIN_PROPOSAL",
        "teacher_origin": "hand-authored source research, not generated by the VOID model",
        "training_admitted": False,
        "expanded_shared_train_groups": 0,
        "final_targets_opened": False,
        "model_optimizer_steps": 0,
        "model_generated_paintings": 0,
        "decision": "PENDING_SHEPHERD_AND_INDEPENDENT_REVIEWER_GLOBAL_SPLIT_ALLOCATION",
    }
    for key, value in exact.items():
        require(type(doc.get(key)) is type(value) and doc[key] == value, "nomination custody/status differs: " + key)
    require(doc["semantics"] == {
        "traversable_rooms": 1,
        "side_service_slots": 2,
        "side_service_slot_width_cells": 3,
        "clearance_route_width_cells": 5,
        "geometric_clearance_only": True,
        "physically_load_bearing_proven": False,
        "gravity_jump_climb_reachability_proven": False,
    }, "physical/geometric semantics cannot be promoted")
    prompt = doc["prompt"]
    require(isinstance(prompt, str) and len(prompt) > 80 and len(prompt) < 900, "request length/shape invalid")
    # No prompt text can mechanically prove artistic semantics: leave independent
    # language/conformance review open and inspect the actual source geometry.
    require(all(term in prompt.lower() for term in (
        "strictly orthographic", "top and bottom", "three staggered",
        "five-cell-wide", "non-traversable service slots"
    )), "nomination omits a critical teacher semantics qualifier")
    proposal = json.loads((ROOT / "v5_support_proposals.json").read_text(encoding="utf-8"))
    witness = program_witness(proposal)
    program = proposal["candidates"][0]["program"]
    require(witness["source_program_sha256"] == doc["program_sha256"]
            and witness["side_service_slot_widths"] == [3, 3]
            and witness["central_geometric_clearance"] == 5,
            "nomination teacher source or clearance differs")
    # The label mask and byte budget must use the existing common trainer's
    # literal SYSTEM, rather than drifting into a lane-invented new framing.
    trainer = ROOT.parents[1] / "training" / "train.py"
    tree = ast.parse(trainer.read_text(encoding="utf-8"))
    system_values = [
        node.value for node in tree.body if isinstance(node, ast.Assign)
        and any(isinstance(target, ast.Name) and target.id == "SYSTEM"
                for target in node.targets)
    ]
    require(len(system_values) == 1 and ast.literal_eval(system_values[0]) == SYSTEM,
            "shared frozen training instruction differs")
    require(FRAMING_ID == "cybersand-void-task-v1"
            and MAX_SEQUENCE_TOKENS == MODEL_CONTEXT,
            "reviewed byte framing/context changed")
    completion = json.dumps(program, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False)
    try:
        encoded = encode_row(CyberSandVoidByteTokenizer(), {
            "id": "A02-V5-REVIEW-ONLY", "prompt": prompt, "completion": completion,
        }, SYSTEM, MODEL_CONTEXT)
    except UnicodeError as exc:
        raise ValueError("invalid strict UTF-8 byte sequence in nomination") from exc
    require(encoded["input_ids"][-1] == 258 and encoded["labels"][-1] == 258
            and len(encoded["input_ids"]) <= MODEL_CONTEXT,
            "VOID complete byte sequence or true EOS differs")
    require(encoded["labels"][:encoded["boundary"]] == [-100] * encoded["boundary"],
            "VOID prefix must remain untrained")
    return {
        "status": "NOMINATION_SOURCE_PASS_NOT_ADMITTED",
        "global_candidate": doc["global_candidate"],
        "model": MODEL,
        "teacher_program_sha256": PROGRAM_SHA,
        "original_native_run_id": 43601866007,
        "original_native_artifact_id": 14116463694,
        "reviewed_teacher_compositions": 1,
        "native_host_seed_variants": 2,
        "prompt_bytes": encoded["prompt_bytes"],
        "completion_bytes": encoded["completion_bytes"],
        "complete_byte_tokens_including_eos": len(encoded["input_ids"]),
        "true_eos_token": 258,
        "full_completion_supervised": True,
        "final_opened": False,
        "new_train_groups": 0,
        "optimizer_steps": 0,
        "requires_global_split_decision": True,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--original-native", type=Path, required=True)
    ap.add_argument("--output", type=Path, required=True)
    args = ap.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    try:
        doc = json.loads((ROOT / "a02_admission_nomination_v1.json").read_text(encoding="utf-8"))
        result = validate(doc)
        native = native_audit(args.original_native)
        require(native["independently_checked_original_native_views"] == 2
                and native["original_crop_sha256"] == CROP_SHA
                and native["original_native_producer"] == PRODUCER
                and native["new_native_art_operations"] == 0,
                "original native evidence/custody differs")
        result["original_native_readbacks_verified"] = 2
        result["original_native_zip_digest_in_prior_custody"] = EXPECTED_ZIP
        result["original_zip_rehashed_this_job"] = False
        result["evidence"] = "existing source-built teacher material only, not model painting"
        result["admission_authority"] = "independent reviewer and shepherd; no shared change"
    except (ValueError, KeyError, TypeError, OSError, UnicodeError) as e:
        result = {"status": "FAIL", "error": str(e),
                  "new_train_groups": 0, "optimizer_steps": 0, "final_opened": False}
    args.output.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps(result, sort_keys=True))
    return 0 if result["status"] == "NOMINATION_SOURCE_PASS_NOT_ADMITTED" else 1


if __name__ == "__main__":
    raise SystemExit(main())
