    all_hashes=set()
    total=[0,0,0,0,0]
    for seed in SEEDS:
        orig=checkpoint_bytes(seed)
        model=Receiver().eval()
        model.load_state_dict(torch.load(io.BytesIO(orig),map_location='cpu',weights_only=True))
