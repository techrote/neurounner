        observation_hashes=[];oracle_actions=[];decisions=[];foreign_decisions=[]
        receipt_file=output/f'h26-ci-regenerated-{seed}.jsonl'
        with receipt_file.open('w') as out:
            for family in FAMILIES:
                for bucket in BUCKETS:
                    x=worlds(seed,family,bucket)
                    hashes=[sha(z.tobytes()) for z in x]
                    require(len(set(hashes))==160 and not(set(hashes)&all_hashes),'duplicate worlds')
                    all_hashes.update(hashes);observation_hashes.extend(hashes)
                    wet=x[...,0]>.5
                    costs=np.stack([(np.where(wet,law,1.)+x[...,1]).sum(-1,dtype='f8') for law in LAWS],axis=1)
                    truth=costs.argmin(-1)
                    logits=score(model,x,donors,SOURCES[0])
