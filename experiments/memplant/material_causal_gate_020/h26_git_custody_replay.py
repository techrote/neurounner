                    acts=logits.argmax(-1);foreign=foreign_logits.argmax(-1)
                    require(np.all((truth[:,0]!=truth[:,1])==bucket.endswith('divergent')),'wrong bucket definition')
                    both=int((acts==truth).all(-1).sum())
                    flip=int((acts[:,0]!=acts[:,1]).sum())
