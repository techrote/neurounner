def sha(raw):return hashlib.sha256(raw).hexdigest()
def require(b,why):
    if not b:raise AssertionError(why)

class Donor(nn.Module):
    def __init__(self):
        super().__init__()
        self.net=nn.Sequential(nn.Linear(4,24),nn.Tanh(),nn.Linear(24,24),nn.Tanh(),nn.Linear(24,1))
    def forward(self,x):return self.net(x).squeeze(-1)

class Receiver(nn.Module):
    def __init__(self):
        super().__init__()
        self.tile=nn.Sequential(nn.Linear(3,16),nn.ReLU(),nn.Linear(16,8),nn.ReLU(),nn.Linear(8,1))
    def forward(self,obs,feature):
        return -self.tile(torch.stack((obs[...,0],obs[...,1],feature),dim=-1)).squeeze(-1).sum(-1)

def open_h22():
    chunks=[REPO/'experiments/memplant/material_causal_gate_020/evidence'/f'h22_capsule.part{i:02}' for i in range(11)]
    require(all(p.exists() for p in chunks),'Git H22 sealed capsule chunks missing')
    raw=b''.join(p.read_bytes() for p in chunks)
    require(sha(raw)==H22_SHA,'H22 capsule identity FAIL')
    return zipfile.ZipFile(io.BytesIO(raw))

def trained_features(capsule):
    nodes,weights=leggauss(5)
    w=np.asarray([a*b/4 for a in weights for b in weights],dtype='f8')
    p=np.zeros((2,25,4),dtype='f4')
    for material in (0,1):
        p[material,:,0]=material;p[material,:,1]=.15
        p[material,:,2:]=[(a,b) for a in nodes for b in nodes]
    out={}
    for source in SOURCES:
        out[source]={}
        for law in (0,1):
            estimates=[]
            for rep in (0,1):
                path=f'source/h21-evidence/fresh-donor-{source}-law{law}-rep{rep}.pt'
                d=Donor().eval()
                d.load_state_dict(torch.load(io.BytesIO(capsule.read(path)),map_location='cpu',weights_only=True))
                with torch.no_grad():
                    estimates.append((d(torch.from_numpy(p)).numpy().astype('f8')@w-.15).astype('f4'))
            out[source][law]=np.mean(estimates,axis=0,dtype='f4')
    return out

def worlds(seed,family,bucket):
    rng=np.random.default_rng(seed+1291000000+134991*(4+FAMILIES.index(family))+31111*BUCKETS.index(bucket))
    obs=[]
    for _ in range(160):
        k=int(rng.integers(2,10));rich=int(rng.integers(2));poor=1-rich
        cnt=[k,k]
        if bucket!='equal_wet_invariant':cnt[rich]=k+1
        wet=np.zeros((2,12),dtype='f4')
        for route in (0,1):
            seq=np.asarray([0,4,8,1,5,9,2,6,10,3,7,11] if family=='quad_stripe' else [0,6,11,5,1,7,10,4,2,8,9,3])
            seq=(seq+int(rng.integers(12)))%12
            if rng.integers(2):seq=(11-seq)%12
            wet[route,seq[:cnt[route]]]=1.
        edge=float(rng.uniform(.008,.030))
        if bucket=='cheap_edge_divergent':delta=.65-edge
        elif bucket=='expensive_edge_divergent':delta=-1.30+edge
        elif bucket=='wet_rich_invariant':delta=-1.30-edge
        elif bucket=='wet_poor_invariant':delta=.65+edge
        else:delta=edge*int(rng.choice([-1,1]))
        fees=.095+.11*rng.beta(.77,3.6,(2,12)) if family=='quad_stripe' else .095+.11*rng.beta(3.6,.77,(2,12))
        correction=(delta-(fees[rich].sum()-fees[poor].sum()))/24.
        fees[rich]+=correction;fees[poor]-=correction
        require(fees.min()>=0 and fees.max()<=.30,'fee bounds')
        tex=rng.uniform(-1,1,(2,12,2)).astype('f4')
        obs.append(np.concatenate((wet[...,None],fees.astype('f4')[...,None],tex),-1).astype('f4'))
    return np.stack(obs).astype('f4')

def score(model,x,donors,source):
    wet=x[...,0]>.5;fee=x[...,1]
    with torch.no_grad():
        return np.stack([model(torch.from_numpy(x),torch.from_numpy(np.where(wet,donors[source][law][1],donors[source][0][0]).astype('f4')+fee)).numpy()
             for law in (0,1)],axis=1)

