def require(ok,why):
    if not ok:
        raise RuntimeError("NCR void1 2048 archive REFUSED: "+why)


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def load_originals(archive_path=ARCHIVE,provenance_path=PROVENANCE):
    p=json.loads(Path(provenance_path).read_text(encoding="utf-8"))
    encoded="".join(Path(archive_path).read_text(encoding="ascii").split())
    require(len(encoded)==7000 and encoded.isascii(),"base64 envelope changed")
    xz=base64.b64decode(encoded,validate=True)
    require(len(xz)==p["archived_originals"]["xz_bytes"]==5248
            and digest(xz)==p["archived_originals"]["xz_sha256"]==XZ_SHA,
            "original XZ source bytes changed")
    raw=lzma.decompress(xz,format=lzma.FORMAT_XZ)
    require(len(raw)==p["archived_originals"]["tar_bytes"]==30720
            and digest(raw)==p["archived_originals"]["tar_sha256"]==TAR_SHA,
            "original USTAR bytes changed")
    out={}
    with tarfile.open(fileobj=io.BytesIO(raw),mode="r:") as tar:
        infos=tar.getmembers()
        require([m.name for m in infos]==sorted(EXPECTED),
                "source member list/count/order changed")
        for m in infos:
            require(m.isfile() and m.name in EXPECTED and m.mode==0o644
                    and m.uid==m.gid==m.mtime==0,
                    "noncanonical source member metadata")
            data=tar.extractfile(m).read()
            size,sha=EXPECTED[m.name]
            src=p["archived_originals"]["originals"][m.name]
            require(m.size==len(data)==size==src["bytes"]
                    and digest(data)==sha==src["sha256"],
                    "original member changed: "+m.name)
            out[m.name]=data
    return out,p


